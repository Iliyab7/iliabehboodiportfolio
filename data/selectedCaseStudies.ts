function localizeStudies(language: Language): CaseStudy[] {
  return selectedStudies.map(({ slug, tools, diagramKind, [language]: study }) => ({
    slug,
    title: study.title,
    category: study.category,
    status: study.status,
    summary: study.summary,
    problem: study.problem,
    solution: study.solution,
    whatIBuilt: study.whatIBuilt,
    tools,
    outcomes: [],
    verification: study.verification,
    process: study.stages,
    impactMetrics: [],
    visual: {
      kind: diagramKind,
      title: study.diagramTitle,
      steps: study.stages,
      example: study.example
    }
  }));
}

export const selectedCaseStudies = {
  en: localizeStudies("en"),
  fa: localizeStudies("fa")
};

export function selectedSlugs(group: Group) {
  return selectedStudies.filter((study) => study.group === group).map((study) => study.slug);
}
